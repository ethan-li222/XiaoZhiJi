  assert.equal(await form.locator('[name="page"]').inputValue(),'2');
  await page.locator('.reader-side-tabs').getByRole('button',{name:'笔记',exact:true}).click();
  await page.getByRole('button',{name:'定位原文',exact:true}).click();
