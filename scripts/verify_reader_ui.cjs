  await page.getByRole('button',{name:'下一页',exact:true}).click();
  await page.locator('.textLayer span').filter({hasText:'Co-citation on second page'}).waitFor();
  await page.waitForFunction(async()=>{const docs=await fetch('/records/document').then(r=>r.json());return (await fetch('/reader/documents/'+docs[0].id).then(r=>r.json())).progress?.page===2;});
