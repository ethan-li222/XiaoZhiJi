const {chromium}=require('../ppt/node_modules/playwright');
const assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch({channel:'chrome',headless:true});
  try{
    const page=await browser.newPage({viewport:{width:1300,height:1000}}), errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.goto(process.argv[2]);
    await page.locator('[data-tab="papers"]').click();
    const form=page.locator('[data-action="papers.related"]');
    await form.evaluate(f=>{f.closest('details').open=true;});
    await form.locator('[name="seed"]').fill('S2:seed');
    await form.locator('[name="similar_limit"]').fill('0');
    await form.locator('button').click();
    await page.locator('.paper-graph-stage svg').waitFor();
    assert.equal(await page.locator('line[data-source="S2:seed"][data-target="S2:ref"][marker-end]').count(),1);
    assert.equal(await page.locator('line[data-source="S2:citing"][data-target="S2:seed"][marker-end]').count(),1);
    if(process.argv[3])await page.locator('.paper-graph-stage').screenshot({path:process.argv[3]});
    await page.getByLabel('关系筛选').selectOption('references');
    assert.equal(await page.locator('.paper-graph-stage line').count(),1);
    await page.getByLabel('关系筛选').selectOption('citations');
    assert.equal(await page.locator('.paper-graph-stage line[data-source="S2:citing"]').count(),1);
    await page.locator('.paper-graph-stage g[data-paper-id="S2:citing"]').focus();
    await page.keyboard.press('Enter');
    assert.ok((await page.locator('.paper-selected').innerText()).includes('Citation'));
    const graphLink=page.locator('#downloads a').filter({hasText:'graph.html'});
    await graphLink.waitFor();
    const exported=await page.request.get(await graphLink.getAttribute('href'));
    assert.ok((await exported.text()).includes('ResearchPapers.mount'));
    await page.getByRole('button',{name:'下一页引用本文',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('line[data-source="S2:next"]'));
    assert.equal(await page.locator('line[data-target="S2:seed"]').count(),1);
    await page.locator('.paper-group[data-direction="citations"]').getByRole('button',{name:'下载 PDF',exact:true}).click();
    const download=await page.waitForEvent('download');
    assert.equal(download.suggestedFilename(),'paper.pdf');
    assert.equal(await download.failure(),null);
    assert.equal((await (await page.request.get(new URL('/records/knowledge',process.argv[2]).href)).json()).length,0);
    const search=page.locator('[data-action="papers.search"]');
    await search.locator('[name="query"]').fill('graph');await search.locator('button').click();
    await page.locator('.paper-card[data-paper-id="https://openalex.org/W9"]').waitFor();
    assert.equal(await page.locator('.paper-card[data-paper-id="https://openalex.org/W9"]').getByRole('button',{name:'下载 PDF',exact:true}).count(),1);
    assert.ok((await page.locator('.paper-card[data-paper-id="https://openalex.org/W10"]').innerText()).includes('暂无开放 PDF'));
    await search.locator('details').evaluate(d=>{d.open=true;});
    await search.locator('[name="mode"]').selectOption('arxiv_browser');
    await search.locator('button').click();
    await page.locator('.paper-card[data-paper-id="arxiv:2401.12345"]').waitFor();
    assert.ok((await page.locator('#result').innerText()).includes('本地 Chrome 搜索来源'));
    assert.ok((await page.locator('#result').innerText()).includes('被引数未知'));
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    assert.deepEqual(errors,[]);
    console.log('Paper UI: directed edges, filtering, selection, pagination, PDF download, search, no automatic knowledge passed');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
